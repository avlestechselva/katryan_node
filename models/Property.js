const mongoose = require('mongoose');

const PropertySchema = new mongoose.Schema({
  propertyID: { type: String, required: true, unique: true },
  department: String,
  displayAddress: String,
  addressPostcode: String,
  address2: String,
  address3: String,
  address4: String,
  displayPropertyType: String,
  propertyBedrooms: mongoose.Schema.Types.Mixed,
  propertyBathrooms: mongoose.Schema.Types.Mixed,
  propertyReceptionRooms: mongoose.Schema.Types.Mixed,
  propertyEnsuites: mongoose.Schema.Types.Mixed,
  propertyKitchens: mongoose.Schema.Types.Mixed,
  price: mongoose.Schema.Types.Mixed,
  rent: mongoose.Schema.Types.Mixed,
  rentFrequency: mongoose.Schema.Types.Mixed,
  mainSummary: String,
  fullDescription: String,
  availability: mongoose.Schema.Types.Mixed,
  forSalePOA: mongoose.Schema.Types.Mixed,
  toLetPOA: mongoose.Schema.Types.Mixed,
  referenceNumber: String,
  latitude: String,
  longitude: String,
  propertyFeature1: String,
  propertyFeature2: String,
  propertyFeature3: String,
  propertyFeature4: String,
  propertyFeature5: String,
  propertyFeature6: String,
  propertyFeature7: String,
  propertyFeature8: String,
  propertyFeature9: String,
  propertyFeature10: String,
}, { timestamps: true, strict: false });

module.exports = mongoose.models.Property || mongoose.model('Property', PropertySchema);
